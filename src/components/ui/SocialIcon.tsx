import type { SVGProps, ComponentType } from "react";

/**
 * Íconos de marcas sociales como SVG inline.
 *
 * Decisión técnica: lucide-react v1.x removió los íconos de marcas
 * (Facebook, Instagram, etc.) por restricciones de uso de marca de
 * cada plataforma. Solución: SVG inline custom siguiendo el lineart
 * minimal del resto del proyecto. Sin dependencias adicionales.
 */

type IconProps = SVGProps<SVGSVGElement>;

